SCHEMA = """
CREATE TABLE IF NOT EXISTS campaigns (
    id TEXT PRIMARY KEY, lead_email TEXT, lead_name TEXT, company TEXT,
    subject TEXT, body TEXT, status TEXT, created_at TEXT, updated_at TEXT, send_error TEXT
);
CREATE TABLE IF NOT EXISTS conversations (
    id TEXT PRIMARY KEY, campaign_id TEXT, inbound_sender TEXT, inbound_subject TEXT,
    inbound_body TEXT, classification TEXT, confidence REAL, draft_subject TEXT,
    draft_body TEXT, status TEXT, created_at TEXT, updated_at TEXT, send_error TEXT
);
"""


@contextmanager
def get_conn():
    conn = sqlite3.connect(SDR_DATABASE_PATH)
    conn.row_factory = sqlite3.Row
    try:
        yield conn
        conn.commit()
    finally:
        conn.close()


def init_db():
    with get_conn() as conn:
        conn.executescript(SCHEMA)


def create_campaign(lead_email, lead_name, company, subject, body, status="pending_approval"):
    cid, ts = str(uuid.uuid4()), _utc_now_iso()
    with get_conn() as conn:
        conn.execute(
            "INSERT INTO campaigns VALUES (?,?,?,?,?,?,?,?,?,?)",
            (cid, lead_email, lead_name, company, subject, body, status, ts, ts, ""),
        )
    return get_campaign(cid)


def get_campaign(cid):
    with get_conn() as conn:
        row = conn.execute("SELECT * FROM campaigns WHERE id=?", (cid,)).fetchone()
        return dict(row) if row else None


def update_campaign(cid, **fields):
    fields["updated_at"] = _utc_now_iso()
    set_clause = ", ".join(f"{k}=?" for k in fields)
    with get_conn() as conn:
        conn.execute(f"UPDATE campaigns SET {set_clause} WHERE id=?", (*fields.values(), cid))
    return get_campaign(cid)


