def _utc_now_iso():
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


# ---------------- llm client ----------------
class LLMUnavailable(Exception):
    pass


def llm_complete(system_prompt, user_prompt, temperature=0.2, max_tokens=800):
    if not GROQ_API_KEY:
        raise LLMUnavailable("No GROQ_API_KEY configured.")
    headers = {"Authorization": f"Bearer {GROQ_API_KEY}", "Content-Type": "application/json"}
    payload  = {
        "model": GROQ_MODEL,
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user",   "content": user_prompt},
        ],
        "temperature": temperature,
        "max_tokens":  max_tokens,
    }
    try:
        resp = requests.post(GROQ_API_URL, headers=headers, json=payload, timeout=30)
    except Exception as exc:
        raise LLMUnavailable(str(exc)) from exc
    if not resp.ok:
        raise LLMUnavailable(f"Groq error {resp.status_code}: {resp.text}")
    try:
        return resp.json()["choices"][0]["message"]["content"].strip()
    except Exception as exc:
        raise LLMUnavailable(f"Unexpected Groq response shape: {exc}") from exc


# ---------------- email provider ----------------
def send_email(to_email: str, subject: str, body: str) -> dict:
    """
    Send an email.

    In test mode (TEST_RECIPIENT is set), all emails are redirected to
    TEST_RECIPIENT so Resend's domain restriction is never hit.
    When TEST_RECIPIENT is empty, the real lead email is used — this requires
    a verified domain configured at resend.com/domains.
    """
    if SDR_OUTREACH_PROVIDER == "dry_run" or not to_email:
        ts = _utc_now_iso()
        print(f"[dry_run] Would send to {to_email} | subject={subject!r}")
        return {"status": "dry_run", "timestamp": ts, "error": ""}

    effective_to = TEST_RECIPIENT if TEST_RECIPIENT else to_email
    if TEST_RECIPIENT and TEST_RECIPIENT != to_email:
        print(f"[resend] ⚠️  test mode — redirecting {to_email} → {effective_to}")

    try:
        r = requests.post(
            RESEND_API_URL,
            headers={
                "Authorization": f"Bearer {RESEND_API_KEY}",
                "Content-Type":  "application/json",
            },
            json={
                "from":    f"{RESEND_SENDER_NAME} <{RESEND_FROM_EMAIL}>",
                "to":      [effective_to],
                "subject": subject,
                "text":    body,
            },
            timeout=30,
        )
        if r.ok:
            ts = _utc_now_iso()
            print(f"[resend] ✅ sent -> {effective_to} at {ts}")
            return {"status": "sent", "timestamp": ts, "error": ""}
        err = f"Resend error {r.status_code}: {r.text}"
        print(f"[resend] ❌ {err}")
        return {"status": "failed", "timestamp": _utc_now_iso(), "error": err}
    except Exception as exc:
        return {"status": "failed", "timestamp": _utc_now_iso(), "error": str(exc)}


