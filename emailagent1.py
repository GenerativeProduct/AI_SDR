# ---------------- outbound: Outreach Agent ----------------
OUTBOUND_SYSTEM_PROMPT = (
    "You are an SDR writing a first-touch cold outbound email. Be concise "
    "(under 150 words), specific to the lead's company and pain points, and "
    "end with a single low-friction call to action. No subject line in the body."
)


class OutboundState(TypedDict, total=False):
    lead_name: str; lead_email: str; company: str; persona: str
    pain_points: str; enrichment_notes: str; offer_summary: str
    draft_subject: str; draft_body: str


def _template_draft(state):
    name    = state.get("lead_name")    or "there"
    company = state.get("company")      or "your team"
    pain    = state.get("pain_points")  or "the challenges your team is navigating"
    offer   = state.get("offer_summary") or "how we help teams like yours"
    subject = f"Quick idea for {company}"
    body    = (
        f"Hi {name},\n\nNoticed {company} has been dealing with {pain}. "
        f"Wanted to share {offer} -- happy to send a 2-minute summary or "
        f"grab 15 minutes if useful.\n\nWorth a quick chat?\n\nBest,\nSDR Team"
    )
    return subject, body


def outbound_build_draft(state):
    user_prompt = (
        f"Lead name: {state.get('lead_name')}\nCompany: {state.get('company')}\n"
        f"Persona: {state.get('persona')}\nPain points: {state.get('pain_points')}\n"
        f"Enrichment notes: {state.get('enrichment_notes')}\n"
        f"Offer summary: {state.get('offer_summary')}\n\nWrite the email body only."
    )
    try:
        body    = llm_complete(OUTBOUND_SYSTEM_PROMPT, user_prompt)
        subject = f"Quick idea for {state.get('company') or 'your team'}"
        print("[outbound] generated via LLM")
        return {"draft_subject": subject, "draft_body": body}
    except LLMUnavailable as exc:
        print(f"[outbound] LLM unavailable ({exc}), using template.")
        subject, body = _template_draft(state)
        return {"draft_subject": subject, "draft_body": body}


def build_outbound_graph():
    g = StateGraph(OutboundState)
    g.add_node("build_draft", outbound_build_draft)
    g.add_edge(START, "build_draft")
    g.add_edge("build_draft", END)
    return g.compile()


def draft_campaign(lead: dict) -> dict:
    result = build_outbound_graph().invoke(lead)
    return {"draft_subject": result["draft_subject"], "draft_body": result["draft_body"]}


# ---------------- inbound: Conversation Agent ----------------
INBOUND_SYSTEM_PROMPT = (
    "You are an SDR replying to an inbound email from a prospect. Write a "
    "short, warm, professional reply appropriate to the classified intent. "
    "Keep it under 120 words."
)

_KEYWORDS = {
    "unsubscribe":    ["unsubscribe", "remove me", "stop emailing", "opt out", "opt-out"],
    "wrong_person":   ["wrong person", "not the right person", "doesn't handle", "not my area"],
    "out_of_office":  ["out of office", "ooo", "on leave", "back on", "vacation"],
    "meeting_request":["meeting", "call", "schedule", "calendar", "book a time", "available"],
    "pricing_request":["price", "pricing", "cost", "quote", "how much", "budget"],
    "objection":      ["not interested", "no budget", "already have", "not a priority", "not now"],
    "interested":     ["interested", "tell me more", "sounds good", "sounds great", "let's talk"],
}


class InboundState(TypedDict, total=False):
    sender: str; subject: str; body: str; normalized_body: str
    classification: str; confidence: float
    draft_subject: str; draft_body: str
    status: Literal["awaiting_approval", "human_review"]


def inbound_read_reply(state):
    return {"normalized_body": re.sub(r"\s+", " ", (state.get("body") or "").strip())}


def inbound_classify_intent(state):
    haystack = f"{(state.get('normalized_body') or '').lower()} {(state.get('subject') or '').lower()}"
    scores = {k: 0.0 for k in _KEYWORDS}
    for label, terms in _KEYWORDS.items():
        for t in terms:
            if t in haystack:
                scores[label] += 1.0
    if "not now" in haystack or "not right now" in haystack:
        scores["objection"] -= 0.5
        scores["not_now"] = scores.get("not_now", 0.0) + 1.5
    best_label, raw = max(scores.items(), key=lambda kv: kv[1])
    if raw <= 0:
        return {"classification": "ambiguous", "confidence": 0.35}
    return {"classification": best_label, "confidence": min(0.95, 0.5 + 0.15 * raw)}


def inbound_route_after_classify(state):
    return "human_review" if (state.get("confidence") or 0.0) < CONFIDENCE_THRESHOLD else "draft_reply"


def _template_inbound_reply(state):
    classification = state.get("classification") or "ambiguous"
    subj = state.get("subject") or "Your message"
    name = (state.get("sender") or "there").split("@", 1)[0].replace(".", " ").title()
    bodies = {
        "meeting_request": f"Hi {name},\n\nHappy to find time -- sharing a scheduling link shortly.\n\nBest,\nSDR Team",
        "pricing_request": f"Hi {name},\n\nThanks for asking -- a teammate will follow up with pricing shortly.\n\nBest,\nSDR Team",
        "objection":       f"Hi {name},\n\nTotally understand, happy to check back another time.\n\nBest,\nSDR Team",
        "not_now":         f"Hi {name},\n\nNo problem -- I'll follow up another time.\n\nBest,\nSDR Team",
        "unsubscribe":     f"Hi {name},\n\nConfirmed -- you won't hear from us again.\n\nBest,\nSDR Team",
        "wrong_person":    f"Hi {name},\n\nThanks for letting me know -- could you point me to the right person?\n\nBest,\nSDR Team",
        "out_of_office":   f"Hi {name},\n\nNo worries -- I'll follow up once you're back.\n\nBest,\nSDR Team",
        "interested":      f"Hi {name},\n\nGreat to hear! Sharing more details shortly.\n\nBest,\nSDR Team",
        "ambiguous":       f"Hi {name},\n\nThanks for the reply -- could you share a bit more on what you're looking for?\n\nBest,\nSDR Team",
    }
    reply_subj = f"Re: {subj}" if not subj.lower().startswith("re:") else subj
    return reply_subj, bodies.get(classification, bodies["ambiguous"])


def inbound_draft_reply(state):
    subj       = state.get("subject") or "Your message"
    reply_subj = f"Re: {subj}" if not subj.lower().startswith("re:") else subj
    user_prompt = (
        f"Sender: {state.get('sender')}\nSubject: {subj}\nBody: {state.get('normalized_body')}\n"
        f"Classified intent: {state.get('classification')} "
        f"(confidence {state.get('confidence', 0):.2f})"
    )
    try:
        body = llm_complete(INBOUND_SYSTEM_PROMPT, user_prompt)
        print("[inbound] generated via LLM")
        return {"draft_subject": reply_subj, "draft_body": body, "status": "awaiting_approval"}
    except LLMUnavailable as exc:
        print(f"[inbound] LLM unavailable ({exc}), using template.")
        s, b = _template_inbound_reply(state)
        return {"draft_subject": s, "draft_body": b, "status": "awaiting_approval"}


def inbound_human_review(state):
    print(f"[inbound] Low confidence ({state.get('confidence', 0):.2f}) -- flagged for review.")
    return {"status": "human_review", "draft_subject": "", "draft_body": ""}


def build_inbound_graph():
    g = StateGraph(InboundState)
    g.add_node("read_reply",       inbound_read_reply)
    g.add_node("classify_intent",  inbound_classify_intent)
    g.add_node("draft_reply",      inbound_draft_reply)
    g.add_node("human_review",     inbound_human_review)
    g.add_edge(START, "read_reply")
    g.add_edge("read_reply", "classify_intent")
    g.add_conditional_edges(
        "classify_intent", inbound_route_after_classify,
        {"draft_reply": "draft_reply", "human_review": "human_review"},
    )
    g.add_edge("draft_reply",  END)
    g.add_edge("human_review", END)
    return g.compile()


def classify_and_draft(sender, subject, body):
    result = build_inbound_graph().invoke({"sender": sender, "subject": subject, "body": body})
    return {
        "classification": result.get("classification"),
        "confidence":     result.get("confidence"),
        "draft_subject":  result.get("draft_subject", ""),
        "draft_body":     result.get("draft_body", ""),
        "status":         result.get("status", "awaiting_approval"),
    }


